// Regenerate the README "Agent behavior" section from src/agents.ts.
// Runs the built CLI so the README always matches what `--facts` prints.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const START = "<!-- facts:start (generated by npm run docs, do not edit) -->";
const END = "<!-- facts:end -->";

const cli = fileURLToPath(new URL("../dist/cli.js", import.meta.url));
const readmePath = fileURLToPath(new URL("../README.md", import.meta.url));

const body = execFileSync(process.execPath, [cli, "--facts", "--format", "markdown"], {
  encoding: "utf8",
}).trimEnd();
const readme = readFileSync(readmePath, "utf8");
const eol = readme.includes("\r\n") ? "\r\n" : "\n";
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start === -1 || end === -1 || end < start) {
  console.error("README.md is missing the facts:start / facts:end markers");
  process.exit(1);
}
const next = `${readme.slice(0, start)}${START}${eol}${eol}${body.replace(/\r?\n/g, eol)}${eol}${eol}${readme.slice(end)}`;
writeFileSync(readmePath, next);
console.log(next === readme ? "README.md is up to date" : "README.md updated");
